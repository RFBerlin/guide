// Generates the files of a researcher's starter project for the RF Berlin HPC servers.
// Used by index.html in the browser and by Node for testing (module.exports).
(function (root) {
  "use strict";

  // CUDA 12.8 is the newest version the RFBerlin-HPC01 driver supports and the oldest that supports
  // the Blackwell GPU in dsserver02, so one base image works on both servers.
  var BASES = {
    python: { image: "ubuntu:24.04", label: "Python (CPU only)" },
    cuda: { image: "nvidia/cuda:12.8.1-cudnn-runtime-ubuntu24.04", label: "Python + CUDA 12.8 (GPU)" },
  };

  var SERVERS = {
    "RFBerlin-HPC01": { gpus: "2x NVIDIA RTX A6000 (48 GB each)", cpu: "112 CPU threads", ram: "125 GB RAM" },
    dsserver02: { gpus: "1x NVIDIA RTX PRO 6000 Blackwell (96 GB)", cpu: "128 CPU threads", ram: "1 TB RAM" },
  };

  function slug(s) {
    return String(s || "").toLowerCase().trim().replace(/[^a-z0-9_-]+/g, "-").replace(/^[-_]+|[-_]+$/g, "").slice(0, 40);
  }

  function lines(s) {
    return String(s || "").split(/[\r\n]+/).map(function (l) { return l.trim(); }).filter(Boolean);
  }

  function aptList(s) {
    return String(s || "").split(/[\s,]+/).map(function (p) { return p.trim(); }).filter(Boolean);
  }

  function validate(o) {
    var errors = {};
    if (!/^[a-z0-9][a-z0-9_-]{1,39}$/.test(o.name || "")) errors.name = "2-40 characters: lowercase letters, digits, - or _.";
    if (!/^[a-z0-9]{4,30}$/.test(o.dockerUser || "")) errors.dockerUser = "Your Docker Hub username (lowercase letters and digits).";
    if (!/^[a-z0-9][a-z0-9._-]{0,127}$/.test(o.imageName || "")) errors.imageName = "Lowercase letters, digits, '.', '-' or '_'.";
    if (!SERVERS[o.server]) errors.server = "Pick a server.";
    if (!BASES[o.base]) errors.base = "Pick an environment.";
    var keys = lines(o.sshKey);
    if (!keys.length || !keys.every(function (k) { return /^(ssh-ed25519|ssh-rsa|ecdsa-sha2-nistp\d+) [A-Za-z0-9+\/=]{40,}( .*)?$/.test(k); }))
      errors.sshKey = "Paste your PUBLIC key (the .pub file), starting with ssh-ed25519 or ssh-rsa.";
    if (/PRIVATE KEY/.test(o.sshKey || "")) errors.sshKey = "That is a PRIVATE key. Never share it - paste the .pub file instead.";
    var badApt = aptList(o.aptPackages).filter(function (p) { return !/^[a-z0-9][a-z0-9.+-]+$/.test(p); });
    if (badApt.length) errors.aptPackages = "Not valid apt package names: " + badApt.join(", ");
    var badPip = lines(o.pythonPackages).filter(function (p) { return !/^([A-Za-z0-9]|--?[a-z])[A-Za-z0-9._\-\[\],<>=!~ ;:"'@\/+]*$/.test(p) && !/^#/.test(p); });
    if (badPip.length) errors.pythonPackages = "Lines that don't look like requirements: " + badPip.join(", ");
    if (lines(o.pythonPackages).some(function (p) { return /^(torch|torchvision|torchaudio)\b/i.test(p); }))
      errors.pythonPackages = "Remove torch from the list and tick 'PyTorch' instead: the default PyPI build needs CUDA 13, which RFBerlin-HPC01 can't run.";
    if (o.pytorch && o.base !== "cuda") errors.pytorch = "PyTorch with GPU needs the 'Python + CUDA' environment.";
    return errors;
  }

  function dockerfile(o) {
    var apt = ["openssh-server", "sudo", "nano", "git", "curl", "ca-certificates", "python3", "python3-venv", "python3-pip"]
      .concat(aptList(o.aptPackages));
    var seen = {};
    apt = apt.filter(function (p) { return seen[p] ? false : (seen[p] = true); });
    return [
      "# Generated by the RF Berlin Container Builder - https://rfberlin.github.io/guide/",
      "# Environment: " + BASES[o.base].label,
      "FROM " + BASES[o.base].image,
      "",
      "ENV DEBIAN_FRONTEND=noninteractive",
      "ENV SSH_PORT=888",
      "",
      "# System packages (add more to the list and push to rebuild)",
      "RUN apt-get update && \\",
      "    apt-get install -y --no-install-recommends \\",
      "      " + apt.join(" \\\n      ") + " && \\",
      "    apt-get clean && rm -rf /var/lib/apt/lists/*",
      "",
      "# SSH: key-only login on port 888",
      "RUN mkdir -p /var/run/sshd && \\",
      "    sed -i \"s/^#\\?Port .*/Port ${SSH_PORT}/\" /etc/ssh/sshd_config && \\",
      "    sed -i 's/^#\\?PubkeyAuthentication .*/PubkeyAuthentication yes/' /etc/ssh/sshd_config && \\",
      "    sed -i 's/^#\\?PasswordAuthentication .*/PasswordAuthentication no/' /etc/ssh/sshd_config",
      "",
      "# User 'ubuntu' (uid 1000) with passwordless sudo inside the container",
      "RUN (id -u ubuntu >/dev/null 2>&1 || useradd -m -s /bin/bash -u 1000 ubuntu) && \\",
      "    usermod -aG sudo ubuntu && \\",
      "    echo 'ubuntu ALL=(ALL) NOPASSWD:ALL' > /etc/sudoers.d/ubuntu && chmod 440 /etc/sudoers.d/ubuntu",
      "",
      "COPY authorized_keys /home/ubuntu/.ssh/authorized_keys",
      "RUN chmod 700 /home/ubuntu/.ssh && chmod 600 /home/ubuntu/.ssh/authorized_keys && \\",
      "    chown -R ubuntu:ubuntu /home/ubuntu/.ssh",
      "",
      "# Python packages in a virtualenv owned by 'ubuntu' (you can pip install more at runtime)",
      "RUN python3 -m venv /opt/venv && chown -R ubuntu:ubuntu /opt/venv",
      "ENV PATH=/opt/venv/bin:$PATH",
      "COPY requirements.txt /tmp/requirements.txt",
      "USER ubuntu",
      "RUN pip install --no-cache-dir --upgrade pip",
    ].concat(o.pytorch ? [
      "# PyTorch built for CUDA 12.8: runs on both servers. (Plain 'pip install torch' pulls a CUDA 13 build",
      "# that needs a newer NVIDIA driver than RFBerlin-HPC01 has.)",
      "RUN pip install --no-cache-dir torch torchvision torchaudio --index-url https://download.pytorch.org/whl/cu128",
    ] : []).concat([
      "RUN pip install --no-cache-dir -r /tmp/requirements.txt",
      "USER root",
      "",
      "COPY start.sh /start.sh",
      "RUN chmod +x /start.sh",
      "",
      "WORKDIR /home/ubuntu/work",
      "EXPOSE ${SSH_PORT}",
      'CMD ["/start.sh"]',
      "",
    ]).join("\n");
  }

  var START_SH = [
    "#!/bin/bash",
    "# Container entrypoint: makes the image's environment visible to SSH sessions and starts sshd.",
    "set -e",
    "printenv | grep -E '^(PATH|LD_LIBRARY_PATH|CUDA_HOME|CUDA_VERSION|NV_[A-Z_]+|NVIDIA_[A-Z_]+)=' > /etc/environment || true",
    "mkdir -p /home/ubuntu/work && chown ubuntu:ubuntu /home/ubuntu/work",
    "ssh-keygen -A",
    "exec /usr/sbin/sshd -D -e",
    "",
  ].join("\n");

  function workflow(o) {
    return [
      "# Builds the image on every push to main and publishes it to Docker Hub.",
      "# The server picks up the new image automatically within ~5 minutes (your container restarts;",
      "# files in /home/ubuntu/work are kept).",
      "name: Build and publish image",
      "",
      "on:",
      "  push:",
      "    branches: [main]",
      "  workflow_dispatch:",
      "",
      "jobs:",
      "  build:",
      "    runs-on: ubuntu-latest",
      "    steps:",
      "      - uses: actions/checkout@v4",
      "      - name: Free disk space for large images",
      "        run: sudo rm -rf /usr/share/dotnet /usr/local/lib/android /opt/ghc /opt/hostedtoolcache/CodeQL",
      "      - uses: docker/setup-buildx-action@v3",
      "      - uses: docker/login-action@v3",
      "        with:",
      "          username: ${{ secrets.DOCKER_USERNAME }}",
      "          password: ${{ secrets.DOCKER_PASSWORD }}",
      "      - uses: docker/build-push-action@v6",
      "        with:",
      "          context: .",
      "          push: true",
      "          tags: " + o.dockerUser + "/" + o.imageName + ":latest",
      "",
    ].join("\n");
  }

  function readme(o) {
    var image = o.dockerUser + "/" + o.imageName;
    return [
      "# " + o.name,
      "",
      "Research environment for the RF Berlin HPC servers, generated by the [Container Builder](https://rfberlin.github.io/guide/).",
      "",
      "| | |",
      "|---|---|",
      "| Image | `" + image + ":latest` |",
      "| Environment | " + BASES[o.base].label + (o.pytorch ? " + PyTorch" : "") + " |",
      "| Server | " + o.server + " |",
      "| GPU | " + o.gpu + " |",
      "| Memory limit | " + o.memory + " |",
      "",
      "## Files",
      "",
      "- `Dockerfile` - the environment. Add system packages to the `apt-get install` list.",
      "- `requirements.txt` - Python packages.",
      "- `authorized_keys` - SSH public key(s) allowed to log in. One per line.",
      "- `start.sh` - starts the SSH server inside the container.",
      "- `.github/workflows/docker-publish.yml` - builds the image and pushes it to Docker Hub on every push to `main`.",
      "",
      "## Changing the environment",
      "",
      "Edit `requirements.txt` or the `Dockerfile`, commit and push. GitHub Actions rebuilds the image and the server",
      "updates your container within about 5 minutes. **Only `/home/ubuntu/work` survives an update** - keep your code",
      "and data there.",
      "",
      "## Connecting",
      "",
      "Once your container is running you get a port number. Then:",
      "",
      "```bash",
      "ssh -p <port> ubuntu@<server address>",
      "```",
      "",
      "For VS Code, install the *Remote - SSH* extension and add this to `~/.ssh/config`:",
      "",
      "```",
      "Host " + o.name,
      "    HostName <server address>",
      "    Port <port>",
      "    User ubuntu",
      "```",
      "",
    ].join("\n");
  }

  function requirements(o) {
    var l = lines(o.pythonPackages);
    return (l.length ? l.join("\n") : "# Add one Python package per line, e.g. numpy") + "\n";
  }

  function files(o) {
    return {
      "Dockerfile": dockerfile(o),
      "requirements.txt": requirements(o),
      "authorized_keys": lines(o.sshKey).join("\n") + "\n",
      "start.sh": START_SH,
      ".github/workflows/docker-publish.yml": workflow(o),
      ".gitignore": ["# Keep data and secrets out of the image and out of git", "data/", "*.env", ".env", "id_*", "!*.pub", ""].join("\n"),
      ".dockerignore": [".git", "data/", "*.env", ".env", ""].join("\n"),
      "README.md": readme(o),
    };
  }

  // Prefilled "Container request" issue (issue form fields are prefilled by their id).
  function requestUrl(o) {
    var q = {
      template: "container-request.yml",
      title: "Container request: " + o.name,
      name: o.name,
      image: o.dockerUser + "/" + o.imageName,
      server: o.server,
      gpu: o.gpu,
      memory: o.memory,
    };
    return "https://github.com/RFBerlin/guide/issues/new?" + Object.keys(q).map(function (k) {
      return encodeURIComponent(k) + "=" + encodeURIComponent(q[k]);
    }).join("&");
  }

  var api = { BASES: BASES, SERVERS: SERVERS, slug: slug, validate: validate, files: files, requestUrl: requestUrl };
  if (typeof module !== "undefined" && module.exports) module.exports = api;
  else root.RFGen = api;
})(this);
